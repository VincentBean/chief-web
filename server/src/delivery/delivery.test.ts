function story(input: Partial<Story> & Pick<Story, 'storyId' | 'priority' | 'status'>): Story {
  return {
    id: 0,
    sessionId: 's',
    title: input.storyId,
    commitSha: null,
    createdAt: '',
    updatedAt: '',
    ...input,
  };
}

describe('the push command', () => {
  it('pushes the branch by name, with an upstream and never a force', () => {
    const spec = pushExecSpec('chief/add-login');
    assert.deepEqual(spec.cmd, ['/bin/sh', '-c', PUSH_SCRIPT]);
    assert.equal(spec.workingDir, CONTAINER_REPO_DIR);
    assert.match(PUSH_SCRIPT, /git push --set-upstream origin "\$CHIEF_FEATURE_BRANCH"/);
    assert.doesNotMatch(PUSH_SCRIPT, /--force|\+refs/);
  });

  it('passes the branch in the environment, never inside the script', () => {
    const spec = pushExecSpec('chief/weird; rm -rf /');
    assert.deepEqual(
      [...(spec.env ?? [])],
      ['CHIEF_FEATURE_BRANCH=chief/weird; rm -rf /', `CHIEF_REPO_DIR=${CONTAINER_REPO_DIR}`],
    );
    assert.doesNotMatch(PUSH_SCRIPT, /rm -rf/);
  });
});

